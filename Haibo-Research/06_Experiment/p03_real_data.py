all_pass = True
for word, a_texts, b_texts, label_a, label_b in WORDS:
    n_a, n_b = len(a_texts), len(b_texts)
    texts = a_texts + b_texts
    vec = TfidfVectorizer(analyzer="char", ngram_range=(1, 2), max_features=500)
    X = vec.fit_transform(texts).toarray()
    pca = PCA(n_components=2)
    X_2d = pca.fit_transform(X)
    explained = pca.explained_variance_ratio_.sum()
    vecs_a, vecs_b = X_2d[:n_a], X_2d[n_a:]
    inner_a = np.mean(cosine_distances(vecs_a))
    inner_b = np.mean(cosine_distances(vecs_b))
    cross = np.mean(cosine_distances(vecs_a, vecs_b))
    ratio = cross / ((inner_a + inner_b) / 2 + 1e-8)
    passed = ratio > 1.2
    status = "✅" if passed else "❌"
    if not passed: all_pass = False
    center_a = vecs_a.mean(axis=0)
    center_b = vecs_b.mean(axis=0)
    print(f"{status} {word}: ratio={ratio:.2f} (阈=1.2), 特征方差={explained:.1%}")
    print(f"   内距({label_a})={inner_a:.3f} 内距({label_b})={inner_b:.3f} 类间={cross:.3f}")
    print(f"   质心({label_a})=({center_a[0]:.4f},{center_a[1]:.4f})")
    print(f"   质心({label_b})=({center_b[0]:.4f},{center_b[1]:.4f})")
    print()

print("=" * 50)
