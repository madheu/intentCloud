# ── 构建实验集 ──
STEPS = [
    {
        "name": "第一步：苹果",
        "class_a": ("科技", APPLE_TECH),
        "class_b": ("水果", APPLE_FRUIT),
    },
    {
        "name": "第二步：杜鹃",
        "class_a": ("花鸟", DUJUAN_FLOWER),
        "class_b": ("地名/鸟", DUJUAN_BIRD),
    },
    {
        "name": "第三步：小米",
        "class_a": ("公司", XIAOMI_COMPANY),
        "class_b": ("粮食", XIAOMI_FOOD),
    },
    {
        "name": "第三步：长城",
        "class_a": ("建筑", CHANGCHENG_CULTURE),
        "class_b": ("品牌/汽车", CHANGCHENG_PRODUCT),
    },
]

# 统计各步数据量
total_step1 = len(APPLE_TECH) + len(APPLE_FRUIT)
total_step2 = total_step1 + len(DUJUAN_FLOWER) + len(DUJUAN_BIRD)
total_step3 = total_step2 + len(XIAOMI_COMPANY) + len(XIAOMI_FOOD) + len(CHANGCHENG_CULTURE) + len(CHANGCHENG_PRODUCT)

print(f"数据量: 第一步={total_step1}, 第二步={total_step2}, 第三步={total_step3}")
print(f"每次扩大: step1→2={total_step2/total_step1:.0%}, step2→3={total_step3/total_step2:.0%}")
print()

all_pass = True

for step in STEPS:
    label_a, texts_a = step["class_a"]
    label_b, texts_b = step["class_b"]
    texts = texts_a + texts_b

    # TF-IDF
    vec = TfidfVectorizer(analyzer="char", ngram_range=(1, 2), max_features=500)
    X = vec.fit_transform(texts).toarray()

    # PCA
    pca = PCA(n_components=2)
    X_2d = pca.fit_transform(X)
    explained = pca.explained_variance_ratio_.sum()

    # 类间/类内距离
    vecs_a = X_2d[:len(texts_a)]
    vecs_b = X_2d[len(texts_a):]
    inner_a = np.mean(cosine_distances(vecs_a))
    inner_b = np.mean(cosine_distances(vecs_b))
    cross = np.mean(cosine_distances(vecs_a, vecs_b))
    avg_inner = (inner_a + inner_b) / 2
    ratio = cross / avg_inner if avg_inner > 0 else float('inf')

    center_a = vecs_a.mean(axis=0)
    center_b = vecs_b.mean(axis=0)

    passed = ratio > 1.2
    status = "✅" if passed else "❌"
    if not passed:
        all_pass = False

    print(f"{status} {step['name']}")
    print(f"   类间/类内比: {ratio:.2f}  (阈值 1.2)")
    print(f"   前2主成分解释方差: {explained:.2%}")
    print(f"   {label_a} 质心: ({center_a[0]:.4f}, {center_a[1]:.4f})")
    print(f"   {label_b} 质心: ({center_b[0]:.4f}, {center_b[1]:.4f})")
    print()

print("=" * 50)
if all_pass:
    print("✅ 全部通过 → H2.0-1 可信度显著提升")
