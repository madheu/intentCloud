# ── 分析 ──
print("控制实验：鲸鱼 vs 汽车（完全不相关概念）")
print()

texts = WHALE + CAR
labels = ["鲸鱼"] * len(WHALE) + ["汽车"] * len(CAR)

vec = TfidfVectorizer(analyzer="char", ngram_range=(1, 2), max_features=500)
X = vec.fit_transform(texts).toarray()

pca = PCA(n_components=2)
X_2d = pca.fit_transform(X)
explained = pca.explained_variance_ratio_.sum()

vecs_a = X_2d[:len(WHALE)]
vecs_b = X_2d[len(WHALE):]

inner_a = np.mean(cosine_distances(vecs_a))
inner_b = np.mean(cosine_distances(vecs_b))
cross = np.mean(cosine_distances(vecs_a, vecs_b))
ratio = cross / ((inner_a + inner_b) / 2 + 1e-8)

center_a = vecs_a.mean(axis=0)
center_b = vecs_b.mean(axis=0)

print(f"类内距离（鲸鱼）: {inner_a:.4f}")
print(f"类内距离（汽车）: {inner_b:.4f}")
print(f"类间距离:          {cross:.4f}")
print(f"类间/类内比:       {ratio:.2f}")
print(f"前2主成分解释方差: {explained:.2%}")
print(f"鲸鱼质心: ({center_a[0]:.4f}, {center_a[1]:.4f})")
print(f"汽车质心: ({center_b[0]:.4f}, {center_b[1]:.4f})")
print()

# ── 自适应判断 ──
if ratio > 1.2:
    print("⚠️  比阈值 1.2 高")
    if ratio > 3.0:
        print(f"   完全不相关概念 = {ratio:.2f} → 高于歧义词（小米 2.81）")
        print("   说明 TF-IDF 在捕捉话题风格差异，不一定是语义分辨率")
    elif ratio > 2.0:
        print(f"   完全不相关概念 = {ratio:.2f} → 接近歧义词范围")
        print("   说明 P0.3 的结果部分来自话题风格差异")
    print("   建议：将 ratio(鲸鱼vs汽车) 作为上限参考值")
    print(f"          真实语义分辨率 = P0.3 ratio / 上限 ratio")
else:
    print("✅  不相关概念不可分 → 控制没问题")
    print("    P0.3 的 ratio 确实是语义分辨率，不是话题风格差异")
